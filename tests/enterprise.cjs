const {createApp}=require('./dom-runtime.cjs');
const assert=require('node:assert/strict');
let count=0;
const check=(name,fn)=>{fn();count++;console.log('PASS',name);};
(async()=>{
 let app=await createApp();
 check('Fresh enterprise preview defaults to light',()=>assert.equal(app.d.documentElement.dataset.theme,'light'));
 app.close();
 app=await createApp({storage:{'nova-theme':'dark'},systemDark:false});
 check('Stored manual dark survives the enterprise default',()=>assert.equal(app.d.documentElement.dataset.theme,'dark'));
 app.setSystemDark(true);app.setSystemDark(false);
 check('System changes do not overwrite manual dark',()=>assert.equal(app.d.documentElement.dataset.theme,'dark'));
 app.close();
 app=await createApp({storage:{'nova-theme':'auto'},systemDark:true});
 check('Stored auto follows initial system dark',()=>{assert.equal(app.d.documentElement.dataset.theme,'dark');assert.equal(app.d.documentElement.dataset.themeMode,'auto');});
 app.setSystemDark(false);
 check('Auto updates when system appearance changes',()=>assert.equal(app.d.documentElement.dataset.theme,'light'));
 app.w.location.hash='settings';await new Promise(r=>setTimeout(r,30));
 const select=app.d.querySelector('#appearance-mode');
 check('Settings exposes explicit auto selection',()=>assert.equal(select.value,'auto'));
 select.value='dark';select.dispatchEvent(new app.w.Event('change',{bubbles:true}));
 check('Manual choice persists and applies immediately',()=>{assert.equal(app.w.localStorage.getItem('nova-theme'),'dark');assert.equal(app.d.documentElement.dataset.theme,'dark');});
 app.d.querySelector('#workspace-name').value='保留未保存输入';
 app.d.querySelector('#workspace-name').dispatchEvent(new app.w.Event('input',{bubbles:true}));
 select.value='auto';select.dispatchEvent(new app.w.Event('change',{bubbles:true}));app.setSystemDark(true);
 check('Appearance changes preserve the unsaved form',()=>assert.equal(app.d.querySelector('#workspace-name').value,'保留未保存输入'));
 app.close();
 app=await createApp({storage:{'nova-theme':'invalid'},systemDark:true});
 check('Invalid preference falls back to enterprise light',()=>assert.equal(app.d.documentElement.dataset.theme,'light'));
 app.close();
 app=await createApp();app.w.location.hash='native-samples';await new Promise(r=>setTimeout(r,30));
 check('Real samples default to enterprise light',()=>assert.ok(app.d.querySelector('#native-preview').src.endsWith('/native-admin/light/changeform.html')));
 let density=app.d.querySelector('#native-density'),look=app.d.querySelector('#native-look');
 density.value='compact';density.dispatchEvent(new app.w.Event('change',{bubbles:true}));
 check('Compact choice loads an actual compact Django export',()=>assert.ok(app.d.querySelector('#native-preview').src.endsWith('/native-admin/compact-light/changeform.html')));
 look.value='auto';look.dispatchEvent(new app.w.Event('change',{bubbles:true}));
 check('Auto and compact compose without a mock CSS switch',()=>assert.ok(app.d.querySelector('#native-preview').src.endsWith('/native-admin/compact-auto/changeform.html')));
 look.value='native';look.dispatchEvent(new app.w.Event('change',{bubbles:true}));
 check('Native comparison disables enterprise density',()=>{assert.ok(density.disabled);assert.ok(app.d.querySelector('#native-preview').src.endsWith('/native-admin/native/changeform.html'));});
 app.close();
 console.log('TOTAL',count,'enterprise preview tests passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
