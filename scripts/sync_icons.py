#!/usr/bin/env python3
"""Generate/check preview icon data from the wheel's package-owned JSON catalog."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "django-theme/src/nova_admin/icons.json"
TARGET = ROOT / "dist/js/icons-data.js"


def generated():
    catalog = json.loads(SOURCE.read_text(encoding="utf-8"))
    seen = set()
    for entry in catalog["icons"]:
        name = entry["name"]
        if not re.fullmatch(r"[a-z][a-z0-9-]*", name) or name in seen:
            raise ValueError(f"Duplicate or invalid icon name: {name}")
        if entry["category"] not in catalog["categories"] or not entry["label"]:
            raise ValueError(f"Invalid catalog metadata: {name}")
        if not re.fullmatch(r"[Mm][MmLlHhVvCcSsQqTtAaZz0-9., +\-]*", entry["path"]):
            raise ValueError(f"SVG must contain path data only: {name}")
        seen.add(name)
    # JSON objects are data, not arbitrary markup. Freeze each public record too.
    categories = json.dumps(catalog["categories"], ensure_ascii=False, separators=(",", ":"))
    icons = json.dumps(catalog["icons"], ensure_ascii=False, separators=(",", ":"))
    return ("// Generated by scripts/sync_icons.py; edit nova_admin/icons.json instead.\n"
            f"// prettier-ignore\nexport const iconCategories = Object.freeze({categories});\n"
            f"// prettier-ignore\nexport const iconCatalog = Object.freeze({icons}.map((entry) => Object.freeze(entry)));\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generated()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            print("Icon data is stale. Run python scripts/sync_icons.py.", file=sys.stderr)
            return 1
        print("Icon catalog and generated preview data match.")
    else:
        TARGET.write_text(content, encoding="utf-8")
        print(f"Generated {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
